async function seed() {
  const collectionRef = db.collection("scholarshipsGuide");
  let added = 0, skipped = 0;
  for (const scholarship of SCHOLARSHIPS) {
    const existing = await collectionRef.where("name", "==", scholarship.name).limit(1).get();
    if (!existing.empty) {
      console.log(`⏭️  متخطّي (موجود بالفعل): ${scholarship.name}`);
      skipped++;
      continue;
    }
    await collectionRef.add({ ...scholarship, updatedAt: Date.now() });
    console.log(`✅ اتضافت: ${scholarship.name}`);
    added++;
  }
  console.log(`\nخلاص: ${added} منحة اتضافت، ${skipped} كانت موجودة من قبل.`);
  process.exit(0);
}

seed().catch(err => {
  console.error("حصل خطأ أثناء الإضافة:", err);
  process.exit(1);
});
